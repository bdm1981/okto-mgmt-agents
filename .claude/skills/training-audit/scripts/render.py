#!/usr/bin/env python3
"""Shared rendering helpers for the per-session report and the dashboard.

Design decision worth keeping: the *numbers* are computed here and the *words*
come from a narrative file the reviewer authors. Nothing in a report is prose
generated by a script, and no tally in a report is a number typed by hand.
"""

import html
import re
from pathlib import Path

ASSETS = Path(__file__).resolve().parent.parent / "assets"

GRADE_CLASS = {
    "wrong_high": "crit",
    "wrong_contained": "warn",
    "incomplete": "info",
    "correct": "good",
    "unverifiable": "",
}
GRADE_LABEL = {
    "wrong_high": "Wrong — high impact",
    "wrong_contained": "Wrong — contained",
    "incomplete": "Incomplete or imprecise",
    "correct": "Verified correct",
    "unverifiable": "Not settled from source",
}
GRADE_ORDER = ["wrong_high", "wrong_contained", "incomplete", "correct", "unverifiable"]

FONTS = (
    '<link rel="preconnect" href="https://fonts.googleapis.com">'
    '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>'
    '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?'
    "family=Zilla+Slab:wght@500;600;700&"
    "family=Source+Sans+3:ital,wght@0,400;0,600;0,700;1,400&"
    'family=IBM+Plex+Mono:wght@400;500&display=swap">'
)


def e(s) -> str:
    return html.escape(str(s if s is not None else ""))


def rich(s) -> str:
    """Escape, then re-allow the small inline vocabulary a reviewer writes:
    `code`, **bold**, *italic*, [text](url).

    Everything is HTML-escaped first, so a transcript quote can never inject
    markup. Link hrefs are restricted to http/https after unescaping the `&amp;`
    that escaping introduced — an unrestricted href here would let a quote carry
    a `javascript:` URL into a published page.
    """
    out = e(s)
    out = re.sub(r"`([^`]+)`", r"<code>\1</code>", out)
    out = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", out)
    out = re.sub(r"(?<!\*)\*([^*]+)\*(?!\*)", r"<em>\1</em>", out)

    def _link(m):
        text, href = m.group(1), m.group(2).replace("&amp;", "&")
        if not re.match(r"https?://", href, re.I):
            return m.group(0)
        return f'<a href="{html.escape(href, quote=True)}">{text}</a>'

    return re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", _link, out)


def head(title: str, standalone: bool) -> str:
    """`standalone` embeds the CSS (for local files and PDF export); the artifact
    build links nothing external beyond fonts, so it embeds too."""
    css = (ASSETS / "report.css").read_text(encoding="utf-8")
    pcss = (ASSETS / "print.css").read_text(encoding="utf-8")
    doc = f"<title>{e(title)}</title>\n{FONTS}\n<style>\n{css}\n{pcss}\n</style>\n"
    if standalone:
        return (
            "<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n"
            '<meta name="viewport" content="width=device-width,initial-scale=1">\n'
            "<style>html{color-scheme:light}body{margin:0}</style>\n" + doc + "</head>\n<body>\n"
        )
    return doc


def tail(standalone: bool) -> str:
    return "</body>\n</html>\n" if standalone else ""


def tally(pairs) -> str:
    cells = "".join(
        f'<div><span class="n {cls}">{n}</span><span class="k">{e(label)}</span></div>'
        for n, label, cls in pairs
    )
    return f'<div class="tally">{cells}</div>'


def meta(pairs) -> str:
    cells = "".join(f"<div><dt>{e(k)}</dt><dd>{rich(v)}</dd></div>" for k, v in pairs)
    return f'<dl class="meta">{cells}</dl>'


def finding(f: dict, num: str) -> str:
    cls = GRADE_CLASS.get(f.get("grade", ""), "")
    parts = [f'<div class="finding {cls}">', '<div class="f-head">']
    parts.append(f'<span class="f-num">{e(num)}</span>')
    parts.append(f'<h3 class="f-title">{rich(f.get("title") or f.get("claim_id",""))}</h3>')
    if f.get("stamp"):
        parts.append(f'<span class="stamp">{e(f["stamp"])}</span>')
    parts.append("</div>")

    if f.get("quote"):
        parts.append(f'<p class="said">{rich(f["quote"])}</p>')
    for para in (f.get("body") or ([f["reality"]] if f.get("reality") else [])):
        parts.append(f"<p>{rich(para)}</p>")
    if f.get("product_bug"):
        parts.append('<p><span class="flag">Product bug</span></p>')
    if f.get("say_instead") or f.get("model_delivery"):
        parts.append('<div class="fix">')
        if f.get("say_instead"):
            parts.append(f'<b>Say instead</b>{rich(f["say_instead"])}')
        if f.get("model_delivery"):
            parts.append(delivery(f["model_delivery"]))
        parts.append("</div>")
    if f.get("evidence"):
        parts.append(
            '<div class="evidence"><b>Evidence</b>' + e(" · ".join(f["evidence"])) + "</div>"
        )
    elif f.get("grade") == "unverifiable":
        parts.append('<div class="evidence"><b>Evidence</b>not settled from source</div>')
    parts.append("</div>")
    return "\n".join(parts)


def delivery(md) -> str:
    """`model_delivery` is a worked example of how the point should have been
    delivered: `{"script": str, "show": [str], "check": str}`. A bare string is
    accepted as the script."""
    if isinstance(md, str):
        md = {"script": md}
    out = ['<div class="delivery"><b>How to deliver it</b>']
    if md.get("script"):
        out.append(f'<p class="script">{rich(md["script"])}</p>')
    if md.get("show"):
        out.append("<p class=\"lbl\">Show on screen</p><ol>")
        out.extend(f"<li>{rich(step)}</li>" for step in md["show"])
        out.append("</ol>")
    if md.get("check"):
        out.append(f'<p><span class="lbl">Check understanding</span> {rich(md["check"])}</p>')
    out.append("</div>")
    return "\n".join(out)


HEALTH_COMPONENTS = [
    ("usage", "Product usage & engagement"),
    ("support", "Support & service activity"),
    ("sentiment", "Sentiment & feedback"),
    ("commercial", "Financial & commercial health"),
]
HEALTH_CLASS = {"healthy": "ok", "watch": "warn", "at_risk": "", "no_signal": "muted"}
HEALTH_LABEL = {"healthy": "Healthy", "watch": "Watch", "at_risk": "At risk", "no_signal": "No signal"}
FOLLOWUP_TYPE = {
    "support_ticket": "Support ticket",
    "bug": "Product bug",
    "feature_request": "Feature request",
    "csm_followup": "CSM follow-up",
    "training_followup": "Training follow-up",
    "billing": "Billing / commercial",
}


def _chip(status: str) -> str:
    cls = HEALTH_CLASS.get(status, "muted")
    return f'<span class="flag {cls}">{e(HEALTH_LABEL.get(status, status or "No signal"))}</span>'


def health_check(hc: dict) -> str:
    """Customer health check section: four signal components, then the
    follow-ups/tickets the session generated. Proposed only — nothing here is
    created in Desk, Sprints or CRM by the audit."""
    out = ["<h2>Customer health check</h2>"]
    head = []
    if hc.get("account"):
        head.append(f"<strong>{rich(hc['account'])}</strong>")
    head.append(f"Overall {_chip(hc.get('overall', 'no_signal'))}")
    out.append(f'<p class="hc-overall">{" · ".join(head)}</p>')
    if hc.get("summary"):
        out.append(f'<p class="sec-note">{rich(hc["summary"])}</p>')
    comps = hc.get("components") or {}
    out.append('<div class="hc-grid">')
    for key, label in HEALTH_COMPONENTS:
        c = comps.get(key) or {}
        out.append('<div class="block">')
        out.append(f"<h3>{e(label)} {_chip(c.get('status', 'no_signal'))}</h3>")
        signals = c.get("signals") or []
        if signals:
            out.append("<ul>" + "".join(f"<li>{rich(x)}</li>" for x in signals) + "</ul>")
        else:
            out.append('<p class="muted">Nothing observed in this session.</p>')
        if c.get("source"):
            out.append(f'<p class="hc-src">Source: {rich(c["source"])}</p>')
        out.append("</div>")
    out.append("</div>")

    fus = hc.get("followups") or []
    out.append("<h2>Follow-ups &amp; tickets to create</h2>")
    if not fus:
        out.append('<p class="sec-note">No follow-up actions came out of this session.</p>')
        return "\n".join(out)
    out.append(
        '<p class="sec-note">Proposed by the audit, not created. Each needs a human to open it '
        "in the right system and assign it.</p>"
    )
    order = {"high": 0, "medium": 1, "low": 2}
    fus = sorted(fus, key=lambda x: order.get(x.get("priority", "medium"), 1))
    rows = [
        [
            f"{i:02d}",
            FOLLOWUP_TYPE.get(x.get("type", ""), x.get("type", "")),
            f"**{x.get('title', '')}**" + (f" — {x['detail']}" if x.get("detail") else ""),
            x.get("owner", "—"),
            (x.get("priority") or "medium").capitalize(),
            f"`{x['stamp']}`" if x.get("stamp") else "—",
            x.get("existing") or "None found",
        ]
        for i, x in enumerate(fus, 1)
    ]
    out.append(table(["#", "Type", "Action", "Owner", "Priority", "At", "Existing ticket"], rows))
    return "\n".join(out)


def table(headers, rows) -> str:
    th = "".join(f"<th>{e(h)}</th>" for h in headers)
    body = "".join(
        "<tr>" + "".join(f"<td>{rich(c)}</td>" for c in r) + "</tr>" for r in rows
    )
    return f'<div class="tw"><table><thead><tr>{th}</tr></thead><tbody>{body}</tbody></table></div>'
